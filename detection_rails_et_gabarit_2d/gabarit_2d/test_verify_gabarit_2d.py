"""Independent verifier tests with tiny synthetic exports, never ML inference.

The fixture uses the real exporter schemas/point writer and geometry helper,
while the verifier implements its own reconstruction and does not import them.
Videos are generated by CPU codecs purely to exercise native PTS bookkeeping.
"""
import copy
import csv
from fractions import Fraction
import json
from pathlib import Path
import tempfile
import unittest

import av
import numpy as np

import infer_gabarit_2d as exporter
from corridor_geometry import analyze_object_mask, corridor_from_rows, extract_contours
import verify_gabarit_2d as verifier


RAIL_FIELDS = ["video_id", "frame_index", "time_video_s", "image_width", "image_height",
               "segment_index", "y_px", "left_raw_px", "right_raw_px", "axis_raw_px",
               "left_display_px", "right_display_px", "axis_display_px", "display_valid", "smoothing_status"]
SOURCE_FRAME_FIELDS = ["video_id", "frame_index", "time_video_s", "image_width", "image_height",
                       "rail_points_raw", "rail_points_displayed", "rail_temporal_status"]


def dump(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")


def table(path, fields, rows):
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def make_video(path, times, codec="libx264", width=32, height=24):
    with av.open(str(path), "w") as output:
        stream = output.add_stream(codec, rate=30)
        stream.width, stream.height, stream.pix_fmt = width, height, "yuv420p"
        stream.time_base = stream.codec_context.time_base = Fraction(1, 1_000_000)
        if codec == "libx264":
            stream.options = {"preset": "ultrafast", "crf": "30"}
        for index, value in enumerate(times):
            image = np.full((height, width, 3), 20 + 40 * index, np.uint8)
            frame = av.VideoFrame.from_ndarray(image, format="bgr24")
            frame.pts, frame.time_base = round(float(value) * 1_000_000), Fraction(1, 1_000_000)
            for packet in stream.encode(frame):
                output.mux(packet)
        for packet in stream.encode():
            output.mux(packet)


def make_delivery(root, litter_on_last_frame=False):
    root = root.resolve()
    source_dir, delivery = root / "source", root / "delivery"
    source_dir.mkdir()
    delivery.mkdir()
    (delivery / "TXT").mkdir()
    source = source_dir / "source.mkv"
    make_video(source, [Fraction(1, 10), Fraction(133, 1000), Fraction(1, 5)], "ffv1")
    with av.open(str(source)) as container:
        frames = list(container.decode(video=0))
    times = [Fraction(frame.pts) * frame.time_base for frame in frames]
    make_video(delivery / "VIDEO_GABARIT_2D.mp4", times)
    axis_rows, original_frames, frame_rows, object_rows, audits, payloads = [], [], [], [], [], []
    dummy_model = source_dir / "synthetic_provenance_only.pt"
    dummy_model.write_bytes(b"synthetic hash fixture, never loaded as model")
    point_total, object_total = 0, 0
    with (delivery / "POINTS_OBJETS.csv").open("w", newline="", encoding="utf-8") as handle:
        point_writer = csv.DictWriter(handle, fieldnames=exporter.POINT_FIELDS)
        point_writer.writeheader()
        for index, native in enumerate(frames):
            base = dict(video_id="SYNTHETIC_FIXTURE", frame_index=index, time_video_s=float(times[index]),
                        source_pts=native.pts, time_base_num=native.time_base.numerator,
                        time_base_den=native.time_base.denominator, image_width=32, image_height=24)
            rail_base = {k: base[k] for k in ("video_id", "frame_index", "time_video_s", "image_width", "image_height")}
            rail_rows = [dict(rail_base, segment_index=(1 if index == 2 and y >= 14 else 0), y_px=y,
                              left_raw_px=12, right_raw_px=18, axis_raw_px=15,
                              left_display_px=12.0, right_display_px=18.0, axis_display_px=15.0,
                              display_valid=True, smoothing_status="initial") for y in (2, 8, 14, 20)]
            axis_rows.extend(rail_rows)
            diagnostic = "no_candidate" if index == 2 else "consistent"
            original_frames.append(dict(rail_base, rail_points_raw=4, rail_points_displayed=4, rail_temporal_status=diagnostic))
            corridor, support, info = corridor_from_rows(rail_rows, 32, 24)
            candidates = []
            if index != 1:
                mask = np.zeros((24, 32), bool)
                if index == 0:
                    mask[4:19, 5:26] = True
                    mask[8:15, 9:23] = False  # real hole, intersects corridor above/below it
                else:
                    mask[7:19, 8:11] = True
                    mask[16:19, 8:18] = True  # L mask with partial rail support
                inside = mask & corridor
                ys, xs = np.nonzero(mask)
                bounds = [int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1]
                obj = dict(model_source="public", class_id=0, class_name="objet_synthetique",
                           confidence_score=0.8, raw_detection_index=0, mask_bbox=bounds,
                           model_bbox_original_px=[float(x) for x in bounds], inference_crop_xyxy=None,
                           touches_crop_border=False, track_id="0:public:0:1", track_confirmed=index == 2,
                           observed_hits=1 if index == 0 else 2,
                           observation_id=f"SYNTHETIC_FIXTURE:f{index:06d}:o000", display_number=1,
                           analysis=analyze_object_mask(mask, corridor, support),
                           full_predicted_mask_contours=extract_contours(mask),
                           corridor_intersection_contours=extract_contours(inside),
                           full_mask_sha256=exporter.mask_sha(mask), intersection_mask_sha256=exporter.mask_sha(inside),
                           mask_quality_score=None, distance_m=None, actual_error_px=None, physical_danger_confirmed=None)
                if litter_on_last_frame and index == 2:
                    obj.update(model_source="litter", class_name="dechet", track_id=None,
                               track_confirmed=False, observed_hits=0,
                               inference_crop_xyxy=exporter.crop_for_corridor(corridor, 0.15))
                candidates.append(obj)
            txt_rel = f"TXT/frame_{index:06d}.txt"
            payload = dict(base, schema_version=1, processing_status="ok",
                           coordinate_convention="original pixel centres, x right, y down",
                           rail_diagnostic_status=diagnostic, rail_support=info, objects=candidates)
            dump(delivery / txt_rel, payload)
            payloads.append(payload)
            for obj in candidates:
                ar, bbox = obj["analysis"], obj["mask_bbox"]
                summary = dict(base, **{k: obj[k] for k in ("observation_id", "track_id", "track_confirmed", "observed_hits",
                                                           "model_source", "class_id", "class_name", "confidence_score", "mask_quality_score")},
                               **{k: ar[k] for k in ("mask_pixel_count", "support_pixel_count", "unsupported_pixel_count", "support_fraction",
                                                     "support_status", "overlap_pixel_count", "overlap_fraction", "overlap_fraction_supported",
                                                     "relation_2d", "relation_reason", "complete_relation_assessment", "touches_image_border")},
                               touches_crop_border=False, mask_x_min_px=bbox[0], mask_y_min_px=bbox[1],
                               mask_x_max_px_exclusive=bbox[2], mask_y_max_px_exclusive=bbox[3],
                               full_mask_sha256=obj["full_mask_sha256"], intersection_mask_sha256=obj["intersection_mask_sha256"],
                               full_contour_count=len(obj["full_predicted_mask_contours"]),
                               intersection_contour_count=len(obj["corridor_intersection_contours"]),
                               txt_file=txt_rel, distance_m=None, actual_error_px=None, physical_danger_confirmed=None)
                object_rows.append(summary)
                point_total += exporter.write_points(point_writer, base, obj, "full_predicted_mask", obj["full_predicted_mask_contours"])
                point_total += exporter.write_points(point_writer, base, obj, "corridor_intersection", obj["corridor_intersection_contours"])
            object_total += len(candidates)
            frame_rows.append(dict(base, processing_status="ok", rail_diagnostic_status=diagnostic,
                                   rail_supported_rows=info["supported_rows"], rail_corridor_pixel_count=info["corridor_pixel_count"],
                                   raw_public_instances=sum(o["model_source"] == "public" for o in candidates),
                                   raw_litter_instances=sum(o["model_source"] == "litter" for o in candidates), merged_instances=len(candidates),
                                   suppressed_duplicate_instances=0, empty_mask_instances=0, overlap_candidates=len(candidates),
                                   confirmed_overlap_candidates=sum(o["track_confirmed"] for o in candidates), indeterminate_instances=0, txt_file=txt_rel))
            audits.append(dict(base, suppressed=[], empty_masks=0,
                               merged_predictions=[{**{k: o[k] for k in ("model_source", "raw_detection_index", "class_name", "confidence_score", "mask_bbox")},
                                                    **{k: o["analysis"][k] for k in ("relation_2d", "overlap_pixel_count", "support_status")}} for o in candidates]))
    table(source_dir / "AXE_ET_LIMITES.csv", RAIL_FIELDS, axis_rows)
    table(delivery / "RAILS.csv", RAIL_FIELDS, axis_rows)
    table(source_dir / "FRAMES.csv", SOURCE_FRAME_FIELDS, original_frames)
    table(delivery / "FRAMES.csv", exporter.FRAME_FIELDS, frame_rows)
    table(delivery / "OBJETS.csv", exporter.OBJECT_FIELDS, object_rows)
    with (delivery / "AUDIT_FUSION.jsonl").open("w", encoding="utf-8") as handle:
        for audit in audits:
            handle.write(json.dumps(audit) + "\n")
    source_meta = dict(status="complete", source=str(source), source_sha256=verifier.sha(source),
                       frames=3, width=32, height=24, video_id="SYNTHETIC_FIXTURE",
                       axis_export_sha256=verifier.sha(source_dir / "AXE_ET_LIMITES.csv"))
    dump(source_dir / "SOURCE_ET_PARAMETRES.json", source_meta)
    frozen = [source, source_dir / "SOURCE_ET_PARAMETRES.json", source_dir / "AXE_ET_LIMITES.csv",
              source_dir / "FRAMES.csv", dummy_model]
    manifest = dict(status="complete", schema_version=1, frames=3, source=str(source), source_sha256=verifier.sha(source),
                    video_id="SYNTHETIC_FIXTURE", rails_recomputed=False, partial_source=False, rail_csv_byte_identical=True,
                    inputs_sha256={str(p): verifier.sha(p) for p in frozen},
                    parameters=dict(rail_delivery=str(source_dir), max_frames=0, public_conf=0.25, litter_conf=0.25, litter_crop_padding=0.15),
                    model_names={"public": {0: "objet_synthetique"}, "litter": {0: "dechet"} if litter_on_last_frame else None},
                    first_time_s=float(times[0]), last_time_s=float(times[-1]),
                    overlap_observations=object_total, point_rows=point_total,
                    output_sha256={name: verifier.sha(delivery / name) for name in verifier.OUTPUTS})
    dump(delivery / "MANIFESTE.json", manifest)
    return delivery


class FullDeliveryTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.delivery = make_delivery(self.root)

    def tearDown(self):
        self.temporary.cleanup()

    def rewrite_txt(self, mutator, index=0):
        path = self.delivery / "TXT" / f"frame_{index:06d}.txt"
        payload = verifier.read_json(path)
        mutator(payload)
        dump(path, payload)

    def refresh_hash(self, filename):
        path = self.delivery / "MANIFESTE.json"
        meta = verifier.read_json(path)
        meta["output_sha256"][filename] = verifier.sha(self.delivery / filename)
        dump(path, meta)

    def change_csv(self, filename, mutator):
        path = self.delivery / filename
        with path.open(newline="") as handle:
            reader = csv.DictReader(handle)
            fields, rows = reader.fieldnames, list(reader)
        mutator(rows)
        table(path, fields, rows)
        self.refresh_hash(filename)

    def expect_failure(self, pattern):
        with self.assertRaisesRegex(ValueError, pattern):
            verifier.verify_delivery(self.delivery)
        self.assertEqual(verifier.read_json(self.delivery / "VERIFICATION.json")["status"], "failed")

    def test_complete_streaming_verification_with_hole_empty_frame_and_native_pts(self):
        report = verifier.verify_delivery(self.delivery)
        self.assertEqual(report["status"], "passed")
        self.assertEqual(report["frames_checked"], 3)
        self.assertEqual(report["objects_checked"], 2)
        self.assertEqual(report["zero_candidate_frames"], 1)
        self.assertGreater(report["contour_holes_checked"], 0)
        self.assertTrue(report["all_candidate_masks_reconstructed"])
        self.assertTrue(report["original_rail_byte_identical"])
        self.assertEqual(report["source_and_rendered_pts_checked"], 3)

    def test_empty_frame_still_requires_txt(self):
        (self.delivery / "TXT/frame_000001.txt").unlink()
        self.expect_failure("one TXT")

    def test_litter_crop_and_unassociated_mask_are_valid(self):
        second = self.root / "with_litter"
        second.mkdir()
        folder = make_delivery(second, litter_on_last_frame=True)
        report = verifier.verify_delivery(folder)
        self.assertEqual(report["objects_checked"], 2)
        self.assertEqual(report["status"], "passed")

    def test_first_exported_track_can_have_two_hits_then_jump_over_unexported_observations(self):
        payload = verifier.read_json(self.delivery / "TXT/frame_000000.txt")
        manifest = verifier.read_json(self.delivery / "MANIFESTE.json")
        with (self.delivery / "OBJETS.csv").open() as handle:
            row = next(csv.DictReader(handle))
        with (self.delivery / "RAILS.csv").open() as handle:
            rails = [r for r in csv.DictReader(handle) if int(r["frame_index"]) == 0]
        corridor, support, _ = verifier.independent_corridor(rails, 32, 24)
        obj = payload["objects"][0]
        base = {key: payload[key] for key in verifier.COMMON}
        history = {}
        # A first exported observation at frame 42 can already be confirmed
        # from a provisional observation or prior observations outside rails.
        for frame_index, hits in ((42, 2), (49, 7)):
            base["frame_index"] = frame_index
            observation = f"SYNTHETIC_FIXTURE:f{frame_index:06d}:o000"
            obj.update(observation_id=observation, observed_hits=hits, track_confirmed=True)
            row.update(observation_id=observation, observed_hits=str(hits), track_confirmed="True")
            verifier.check_object(obj, row, base, corridor, support, manifest, 0, 0, history)
        self.assertEqual(history[obj["track_id"]], (49, 7))
        # The sparse export still must not repeat or decrease an observed count.
        base["frame_index"] = 50
        obj["observation_id"] = row["observation_id"] = "SYNTHETIC_FIXTURE:f000050:o000"
        with self.assertRaisesRegex(ValueError, "non-increasing observed hits"):
            verifier.check_object(obj, row, base, corridor, support, manifest, 0, 0, history)
        with self.assertRaisesRegex(ValueError, "generation/source/class mismatch"):
            verifier.check_object(obj, row, base, corridor, support, manifest, 0, 1, {})

    def test_declared_partial_prefix_keeps_native_indices_and_source_rail_rows(self):
        (self.delivery / "TXT/frame_000002.txt").unlink()
        for name in ("FRAMES.csv", "OBJETS.csv", "POINTS_OBJETS.csv", "RAILS.csv"):
            self.change_csv(name, lambda rows: rows.__setitem__(slice(None), [r for r in rows if int(r["frame_index"]) < 2]))
        audit_path = self.delivery / "AUDIT_FUSION.jsonl"
        audit_path.write_text("".join(audit_path.read_text().splitlines(keepends=True)[:2]))
        make_video(self.delivery / "VIDEO_GABARIT_2D.mp4", [0.1, 0.133])
        path = self.delivery / "MANIFESTE.json"
        meta = verifier.read_json(path)
        with (self.delivery / "POINTS_OBJETS.csv").open() as handle:
            point_count = sum(1 for _ in csv.DictReader(handle))
        meta.update(frames=2, partial_source=True, rail_csv_byte_identical=False,
                    last_time_s=0.133, overlap_observations=1, point_rows=point_count)
        meta["parameters"]["max_frames"] = 2
        meta["output_sha256"] = {name: verifier.sha(self.delivery / name) for name in verifier.OUTPUTS}
        dump(path, meta)
        report = verifier.verify_delivery(self.delivery)
        self.assertEqual(report["status"], "passed")
        self.assertEqual(report["frames_checked"], 2)
        self.assertFalse(report["original_rail_byte_identical"])

    def test_unknown_distance_must_not_be_zero(self):
        self.rewrite_txt(lambda p: p["objects"][0].update(distance_m=0))
        self.expect_failure("unknown must be null/empty")

    def test_optional_raw_rectangle_overlap_is_recomputed(self):
        path = self.delivery / "AUDIT_FUSION.jsonl"
        records = [json.loads(line) for line in path.read_text().splitlines()]
        records[0]["merged_predictions"][0]["bbox_overlap_pixel_count"] = 0
        path.write_text("".join(json.dumps(row) + "\n" for row in records))
        self.refresh_hash("AUDIT_FUSION.jsonl")
        self.expect_failure("Audit rectangle overlap differs")

    def test_hole_flag_cannot_be_dropped(self):
        def corrupt(payload):
            hole = next(c for c in payload["objects"][0]["full_predicted_mask_contours"] if c["is_hole"])
            hole["is_hole"] = False
        self.rewrite_txt(corrupt)
        self.expect_failure("depth/hole")

    def test_intersection_must_equal_true_mask_and_rail(self):
        def corrupt(payload):
            obj = payload["objects"][0]
            obj["corridor_intersection_contours"] = copy.deepcopy(obj["full_predicted_mask_contours"])
        self.rewrite_txt(corrupt)
        self.expect_failure("Intersection mask differs")

    def test_every_point_row_is_checked_even_after_output_hash_updated(self):
        self.change_csv("POINTS_OBJETS.csv", lambda rows: rows[-1].update(x_px="-1"))
        self.expect_failure("invalid integer")

    def test_native_pts_cannot_be_replaced_by_index_over_fps(self):
        self.change_csv("FRAMES.csv", lambda rows: rows[0].update(time_video_s="0.0"))
        self.expect_failure("source PTS mismatch")

    def test_original_rail_byte_identity_is_checked(self):
        self.change_csv("RAILS.csv", lambda rows: rows[0].update(left_raw_px="11"))
        self.expect_failure("byte-identical")

    def test_rendered_extra_frame_is_detected(self):
        make_video(self.delivery / "VIDEO_GABARIT_2D.mp4", [0.1, 0.133, 0.2, 0.233])
        self.refresh_hash("VIDEO_GABARIT_2D.mp4")
        self.expect_failure("extra frames")

    def test_rendered_clock_shift_is_detected(self):
        make_video(self.delivery / "VIDEO_GABARIT_2D.mp4", [0.0, 0.033, 0.1])
        self.refresh_hash("VIDEO_GABARIT_2D.mp4")
        self.expect_failure("shifted, duplicated or resampled")

    def test_object_mask_hash_is_checked(self):
        self.rewrite_txt(lambda p: p["objects"][0].update(full_mask_sha256="0" * 64))
        self.expect_failure("Full mask SHA")

    def test_duplicate_json_keys_are_rejected(self):
        path = self.delivery / "TXT/frame_000001.txt"
        content = path.read_text()
        path.write_text(content.replace('"objects": []', '"objects": [], "objects": []'))
        self.expect_failure("Duplicate JSON key")


if __name__ == "__main__":
    unittest.main(verbosity=2)
